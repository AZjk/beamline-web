/**
 * Generate TypeScript types from each app's committed OpenAPI document:
 * apps/<app>/openapi.json -> apps/<app>/src/api/schema.d.ts
 *
 * The document comes from the tool's own export command (for pyXpcsViewer:
 * `pyxpcsviewer-web --export-openapi`). CI regenerates the types and fails when they differ from
 * the committed ones, so the frontend never drifts from the API it was written against.
 */
import { existsSync, readdirSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const appsDir = path.join(root, "apps");
const header = [
  "// Copyright © UChicago Argonne LLC",
  "// See LICENSE file for details",
  "/* Generated by `pnpm gen:types` from openapi.json. Do not edit. */",
  "",
].join("\n");

let count = 0;
for (const app of readdirSync(appsDir)) {
  const spec = path.join(appsDir, app, "openapi.json");
  if (!existsSync(spec)) continue;
  const document = JSON.parse(await readFile(spec, "utf8"));
  const ast = await openapiTS(document, { alphabetize: true, defaultNonNullable: false });
  const out = path.join(appsDir, app, "src", "api", "schema.d.ts");
  await mkdir(path.dirname(out), { recursive: true });
  await writeFile(out, header + astToString(ast));
  console.log(`${path.relative(root, spec)} -> ${path.relative(root, out)}`);
  count += 1;
}
if (count === 0) console.warn("no apps/*/openapi.json found");
